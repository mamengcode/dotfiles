#!/bin/bash
# Safe, repeatable bootstrap for this macOS workstation.
# This script never authenticates services and never removes packages.
set -euo pipefail

repo_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)"
with_optional=0
for arg in "$@"; do
	case "$arg" in
	--with-optional)
		with_optional=1
		;;
	*)
		echo "Usage: $0 [--with-optional]" >&2
		exit 2
		;;
	esac
done

# Prefer an existing native Apple Silicon Homebrew installation. Installing
# Homebrew is intentionally limited to an explicit manual invocation of this
# script; it is not performed by shell startup files.
if ! command -v brew >/dev/null 2>&1; then
	if [[ -x /opt/homebrew/bin/brew ]]; then
		eval "$(/opt/homebrew/bin/brew shellenv)"
	elif [[ -x /usr/local/bin/brew ]]; then
		eval "$(/usr/local/bin/brew shellenv)"
	else
		echo "Homebrew is not installed; installing it now because bootstrap.sh was run manually."
		/bin/bash -c "$(curl -fsSL https://raw.githubusercontent.com/Homebrew/install/HEAD/install.sh)"
		if [[ -x /opt/homebrew/bin/brew ]]; then
			eval "$(/opt/homebrew/bin/brew shellenv)"
		elif [[ -x /usr/local/bin/brew ]]; then
			eval "$(/usr/local/bin/brew shellenv)"
		else
			echo "Homebrew installation completed but brew was not found." >&2
			exit 1
		fi
	fi
fi

# The default bundle is deliberately limited to shared command-line and build
# tools. It never cleans up packages that are not listed.
brew bundle --no-upgrade --file="$repo_dir/Brewfile"

# Personal GUI apps, project-specific tools, VS Code extensions, and npm
# packages are opt-in because they may be hardware-, policy-, or account-
# specific.
if (( with_optional )); then
	brew bundle --no-upgrade --file="$repo_dir/Brewfile.optional"
fi

if ! command -v chezmoi >/dev/null 2>&1; then
	echo "chezmoi is unavailable after brew bundle." >&2
	exit 1
fi

# Keep the source location in chezmoi's normal per-machine config so regular
# `chezmoi status/diff/apply` commands work after bootstrap. Do not replace an
# existing user-managed config.
chezmoi_config="$HOME/.config/chezmoi/chezmoi.toml"
if [[ ! -f "$chezmoi_config" ]]; then
	mkdir -p "$(dirname -- "$chezmoi_config")"
	escaped_repo_dir="${repo_dir//\\/\\\\}"
	escaped_repo_dir="${escaped_repo_dir//\"/\\\"}"
	printf '# Generated by dotfiles/bootstrap.sh.\nsourceDir = "%s"\n' \
		"$escaped_repo_dir" > "$chezmoi_config"
fi

# Only files represented in the chezmoi source layout are applied. Repository
# metadata and documentation are excluded by .chezmoiignore. Without --force,
# modified managed files are surfaced for review rather than overwritten.
chezmoi --source="$repo_dir" --destination="$HOME" apply

# Install the configured global runtimes after their mise config is applied.
if command -v mise >/dev/null 2>&1; then
	mise -C "$repo_dir" install
fi

# Chezmoi's portable default mode is not sufficient for SSH configuration.
chmod 700 "$HOME/.ssh"
chmod 600 "$HOME/.ssh/config"

echo "Bootstrap complete. No service authentication was performed."
